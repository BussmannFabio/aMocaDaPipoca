  expect(email).toBeTruthy();
  await page.goto(email.reset_url);
  await page.getByLabel('Nova senha', { exact: true }).fill('NovaPipoca@456');
  await page.getByRole('button', { name: 'Salvar nova senha' }).click();
  await expect(page.getByText(/Senha atualizada/)).toBeVisible();
  await page.getByRole('link', { name: 'Voltar para entrar' }).click();
  await page.getByLabel('E-mail', { exact: true }).fill(clientEmail);
  await page.getByLabel('Senha', { exact: true }).fill('NovaPipoca@456');
  await page.getByRole('button', { name: 'Entrar na minha conta' }).click();
  await expect(page).toHaveURL(/\/encomendar$/);
  const replay = await page.request.post('/api/auth/reset', { headers: { Origin: 'http://127.0.0.1:3000' }, data: { token: new URL(email.reset_url).searchParams.get('token'), password: 'OutraPipoca@789' } });
  expect(replay.status()).toBe(400);
